// Convierte la VAPID public key (base64url) a Uint8Array para pushManager.subscribe.
// El buffer se aloca explicito para que el tipo sea `Uint8Array<ArrayBuffer>` y no
// `Uint8Array<ArrayBufferLike>`: `applicationServerKey` pide un BufferSource, que
// excluye SharedArrayBuffer.
export function urlBase64ToUint8Array(base64String: string): Uint8Array<ArrayBuffer> {
  const padding = '='.repeat((4 - (base64String.length % 4)) % 4);
  const base64 = (base64String + padding).replace(/-/g, '+').replace(/_/g, '/');
  const raw = atob(base64);
  const output = new Uint8Array(new ArrayBuffer(raw.length));
  for (let i = 0; i < raw.length; i++) output[i] = raw.charCodeAt(i);
  return output;
}

export function isWebPushSupported(): boolean {
  return (
    typeof window !== 'undefined' &&
    'serviceWorker' in navigator &&
    'PushManager' in window &&
    'Notification' in window
  );
}
